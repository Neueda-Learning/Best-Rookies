function detectInitialLocale() {
  if (typeof window === 'undefined') {
    return 'en'
  }

  const savedLocale = window.localStorage.getItem(STORAGE_KEY)

  if (savedLocale === 'zh' || savedLocale === 'en') {
    return savedLocale
  }

  return window.navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

const locale = ref(detectInitialLocale())

if (typeof document !== 'undefined') {
  watch(
    locale,
    (value) => {
      document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en'
    },
    { immediate: true }
  )
}

function interpolate(message, params = {}) {
  return message.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`))
}

export function setLocale(nextLocale) {
  if (nextLocale !== 'zh' && nextLocale !== 'en') {
    return
  }

  locale.value = nextLocale

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, nextLocale)
  }
}

export function toggleLocale() {
  setLocale(locale.value === 'zh' ? 'en' : 'zh')
}

export function getLocale() {
  return locale.value
}

export function t(key, params) {
  const activeMessages = messages[locale.value] || messages.en
  const fallbackMessages = messages.en
  const message = activeMessages[key] ?? fallbackMessages[key] ?? key

  return typeof message === 'string' ? interpolate(message, params) : key
}

export function useI18n() {
  return {
    locale,
    isZh: computed(() => locale.value === 'zh'),
    setLocale,
    toggleLocale,
    t
  }
}